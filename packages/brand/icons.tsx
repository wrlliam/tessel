export const TILE_ICON_NAMES = Object.keys(TILE_ICONS)

/** An emoji or other short text used as an icon instead of a named one. */
const isGlyph = (icon: string) => !Object.hasOwn(TILE_ICONS, icon) && [...icon].length <= 2

export function TileIcon({
  icon,
  size,
  className,
}: {
  icon: string | undefined
  size: number
  className?: string
}) {
  if (!icon) return null
  const Icon = Object.hasOwn(TILE_ICONS, icon) ? TILE_ICONS[icon] : undefined
  if (Icon) return <Icon size={size} strokeWidth={2} className={className} aria-hidden />
  if (isGlyph(icon)) {
    return (
      <span className={className} style={{ fontSize: size, lineHeight: 1 }} aria-hidden>
        {icon}
      </span>
    )
  }
  return null
}
